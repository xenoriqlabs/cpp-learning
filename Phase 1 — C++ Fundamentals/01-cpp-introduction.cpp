// 1. What is C++

/*
C++ is a general-purpose, compiled programming language.
It was developed by Bjarne Stroustrup.
C++ supports multiple programming paradigms, including:
- Procedural programming
- Object-Oriented Programming (OOP)
- Generic programming
- Functional programming

C++ is known for:
- High performance
- Low-level memory control
- Object-Oriented Programming
- Powerful Standard Library
- Portability

C++ is commonly used when performance and control over
system resources are important.
*/

// 2. History of C++

/*
C++ was created by Bjarne Stroustrup at Bell Labs.

Important milestones:

1979
- Bjarne Stroustrup started working on "C with Classes".

1983
- The language was renamed C++.

1985
- The first commercial version of C++ was released.

1998
- C++98 became the first standardized version of C++.

2003
- C++03 was released as an update to C++98.

2011
- C++11 introduced many modern features such as:
  - auto
  - nullptr
  - lambda expressions
  - range-based for loops
  - smart pointers

2014
- C++14 improved and extended C++11 features.

2017
- C++17 introduced additional modern language features.

2020
- C++20 introduced major features such as:
  - Concepts
  - Ranges
  - Coroutines
  - Modules

2023
- C++23 continued improving the language and Standard Library.

C++ continues to evolve through new standards.
*/

// 3. C++ vs C

/*
C:
- Procedural programming language
- Developed earlier than C++
- Does not have built-in classes and objects
- Commonly used for operating systems and embedded systems

C++:
- Supports procedural programming
- Supports Object-Oriented Programming
- Supports classes and objects
- Supports templates and generic programming
- Provides more abstraction features

Example:

C:
    printf("Hello World");

C++:
    cout << "Hello World";

Main difference:
C focuses mainly on procedural programming, while C++ supports procedural, object-oriented,
and generic programming.
*/

// 4. C++ vs Java

/*
C++:
- Compiled directly to machine code
- Generally provides very high performance
- Allows direct memory management
- Supports pointers
- Supports multiple inheritance of classes
- Commonly used for systems and performance-critical software

Java:
- Compiled into bytecode
- Runs on the Java Virtual Machine (JVM)
- Uses automatic garbage collection
- Does not provide traditional pointer manipulation
- Designed for portability across platforms
- Commonly used for enterprise applications and Android
  development historically

Main difference:
C++ gives more control over hardware and memory,
while Java provides more managed memory and portability.
*/

// 5. C++ vs Python

/*
C++:
- Compiled language
- Generally faster for CPU-intensive tasks
- Statically typed
- Provides direct memory management
- More complex syntax
- Commonly used for game engines, systems, and
  performance-critical applications

Python:
- Dynamically typed
- Generally easier to learn and write
- Automatic memory management
- Usually slower than C++ for CPU-intensive code
- Large ecosystem for AI, Machine Learning,
  Data Science, and Automation

Main difference:
C++ focuses more on performance and low-level control,
while Python focuses more on simplicity and productivity.
*/

