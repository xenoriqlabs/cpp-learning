#include <iostream>
using namespace std;

int main()
{

    int num1 = 20;
    int num2 = 10;

    // ========================================
    // 1. == Equal To
    // ========================================

    cout << "num1 == num2: "
         << (num1 == num2) << endl;

    // ========================================
    // 2. != Not Equal To
    // ========================================

    cout << "num1 != num2: "
         << (num1 != num2) << endl;

    // ========================================
    // 3. > Greater Than
    // ========================================

    cout << "num1 > num2: "
         << (num1 > num2) << endl;

    // ========================================
    // 4. < Less Than
    // ========================================

    cout << "num1 < num2: "
         << (num1 < num2) << endl;

    // ========================================
    // 5. >= Greater Than or Equal To
    // ========================================

    cout << "num1 >= num2: "
         << (num1 >= num2) << endl;

    // ========================================
    // 6. <= Less Than or Equal To
    // ========================================

    cout << "num1 <= num2: "
         << (num1 <= num2) << endl;

    return 0;
}